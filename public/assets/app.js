/* Personalized Weekly Briefing — dashboard behaviour.
   Renders from public/data/briefings.json (generated by scripts/build.mjs):
   the sidebar lists every briefing, the right pane shows its story cards. */

const ACCENTS = ['blue', 'teal', 'amber', 'purple', 'coral'];
const KIND_LABEL = { weekly: 'Weekly', daily: 'Daily' };

const state = {
  data: { briefings: [], generatedAt: null },
  slug: null,      // null = overview
  topic: 'all',
  query: '',
};

const els = {
  nav: document.getElementById('nav'),
  view: document.getElementById('view'),
  eyebrow: document.getElementById('topbar-eyebrow'),
  title: document.getElementById('topbar-title'),
  actions: document.getElementById('topbar-actions'),
  search: document.getElementById('search'),
  count: document.getElementById('brief-count'),
  toast: document.getElementById('toast'),
};

/* --------------------------------------------------------------- utilities */

const escapeHtml = (value) => String(value ?? '')
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;')
  .replace(/'/g, '&#39;');

const accentClass = (accent) => `accent-${ACCENTS.includes(accent) ? accent : 'blue'}`;

const byId = (slug) => state.data.briefings.find((brief) => brief.slug === slug) ?? null;

const icon = {
  search: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><circle cx="11" cy="11" r="7"/><path d="m20 20-3.6-3.6"/></svg>',
  external: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M14 4h6v6"/><path d="M20 4 11 13"/><path d="M18 14v4a2 2 0 0 1-2 2H6a2 2 0 0 1-2-2V8a2 2 0 0 1 2-2h4"/></svg>',
  copy: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><rect x="9" y="9" width="11" height="11" rx="2"/><path d="M5 15V6a2 2 0 0 1 2-2h8"/></svg>',
  menu: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><path d="M4 7h16M4 12h16M4 17h16"/></svg>',
  sun: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round"><circle cx="12" cy="12" r="4.2"/><path d="M12 3v2M12 19v2M3 12h2M19 12h2M5.6 5.6 7 7M17 17l1.4 1.4M18.4 5.6 17 7M7 17l-1.4 1.4"/></svg>',
  moon: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M20 14.5A8.5 8.5 0 1 1 9.5 4a6.8 6.8 0 0 0 10.5 10.5Z"/></svg>',
};

function toast(message) {
  els.toast.textContent = message;
  els.toast.classList.add('show');
  clearTimeout(toast.timer);
  toast.timer = setTimeout(() => els.toast.classList.remove('show'), 1800);
}

async function copyText(text) {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const area = document.createElement('textarea');
    area.value = text;
    area.setAttribute('readonly', '');
    area.style.position = 'fixed';
    area.style.opacity = '0';
    document.body.append(area);
    area.select();
    const ok = document.execCommand?.('copy') ?? false;
    area.remove();
    return ok;
  }
}

/* ------------------------------------------------------------------ search */

function matchesQuery(brief, story, query) {
  if (!query) return true;
  const haystack = [
    brief.title, brief.theme, brief.deck, brief.kind, brief.dateLabel,
    story?.headline, story?.summary, story?.whyItMatters, story?.whatChanged,
    story?.prompt, story?.chips?.join(' '), story?.topics?.join(' '),
  ].filter(Boolean).join(' ').toLowerCase();
  return query.toLowerCase().split(/\s+/).every((term) => haystack.includes(term));
}

/* --------------------------------------------------------------- rendering */

function renderSidebar() {
  const groups = [
    { kind: 'weekly', label: 'Weekly briefings' },
    { kind: 'daily', label: 'Daily briefings' },
  ];

  const overview = `
    <div class="nav-group">
      <button class="nav-item" data-route="" aria-current="${state.slug === null}">
        <span class="dot" style="--accent: var(--blue)"></span>
        <span class="nav-body">
          <span class="nav-title">All briefings</span>
          <span class="nav-meta">Dashboard overview</span>
        </span>
        <span class="count">${state.data.briefings.length}</span>
      </button>
    </div>`;

  const sections = groups.map(({ kind, label }) => {
    const items = state.data.briefings.filter((brief) => brief.kind === kind);
    if (!items.length) return '';
    return `
      <div class="nav-group">
        <div class="nav-label">${label}</div>
        ${items.map((brief, index) => `
          <button class="nav-item" data-route="${brief.slug}" aria-current="${state.slug === brief.slug}">
            <span class="dot" style="--accent: var(--${ACCENTS[index % ACCENTS.length]})"></span>
            <span class="nav-body">
              <span class="nav-title">${escapeHtml(brief.theme || brief.title)}</span>
              <span class="nav-meta">${escapeHtml(`${brief.weekday}, ${brief.dateLabel}`)}</span>
            </span>
            <span class="count">${brief.storyCount}</span>
          </button>`).join('')}
      </div>`;
  }).join('');

  els.nav.innerHTML = overview + sections;
}

function artMarkup(story, fallbackLabel) {
  if (story?.art) return story.art;
  return `<span class="index">${escapeHtml(fallbackLabel)}</span>`;
}

function linksMarkup(links) {
  return (links ?? []).map((link) => `
    <a href="${escapeHtml(link.href)}" target="_blank" rel="noopener">${escapeHtml(link.label)} ${icon.external}</a>`).join('');
}

function storyCard(brief, story, index, { showSource = false } = {}) {
  const promptId = `${brief.slug}-${story.id}`;
  const tryText = story.tryThis && story.prompt && story.tryThis.startsWith(story.prompt.slice(0, 40))
    ? ''
    : story.tryThis;
  const extras = [
    story.whatChanged && `<div class="note"><b>What changed</b>${escapeHtml(story.whatChanged)}</div>`,
    tryText && `<div class="note"><b>Try this</b>${escapeHtml(tryText)}</div>`,
    story.watchFor && `<div class="note"><b>What to watch</b>${escapeHtml(story.watchFor)}</div>`,
    story.prompt && `
      <div class="prompt" data-prompt="${promptId}">
        <code>${escapeHtml(story.prompt)}</code>
        <div class="prompt-actions">
          <button class="btn" data-copy="${promptId}">${icon.copy} Copy prompt</button>
          ${story.prompt.length > 260 ? `<button class="btn btn-ghost" data-expand="${promptId}">Show full</button>` : ''}
        </div>
      </div>`,
  ].filter(Boolean).join('');

  return `
    <article class="card ${accentClass(story.accent)}" id="${escapeHtml(`${brief.slug}--${story.id}`)}">
      <div class="card-art">${artMarkup(story, String(index + 1).padStart(2, '0'))}</div>
      <div class="card-body">
        <div class="chips">
          ${showSource ? `<span class="chip">${escapeHtml(`${KIND_LABEL[brief.kind]} · ${brief.shortDate}`)}</span>` : ''}
          ${(story.chips ?? []).map((chip) => `<span class="chip">${escapeHtml(chip)}</span>`).join('')}
        </div>
        <h4>${escapeHtml(story.headline)}</h4>
        ${story.summary ? `<p class="summary">${escapeHtml(story.summary)}</p>` : ''}
        ${story.whyItMatters ? `<div class="note"><b>Why it matters to you</b>${escapeHtml(story.whyItMatters)}</div>` : ''}
        ${extras ? `
          <details class="more">
            <summary>Details, prompt and limits</summary>
            <div class="more-body">${extras}</div>
          </details>` : ''}
      </div>
      <div class="card-foot">
        ${linksMarkup(story.links)}
        <span class="spacer"></span>
        <a href="${escapeHtml(`${brief.file}#${story.id}`)}" target="_blank" rel="noopener">In briefing ${icon.external}</a>
      </div>
    </article>`;
}

function briefCard(brief, index) {
  const art = brief.stories.find((story) => story.art);
  return `
    <article class="card brief-card ${accentClass(ACCENTS[index % ACCENTS.length])}">
      <div class="card-art">
        <span class="kind">${escapeHtml(KIND_LABEL[brief.kind] ?? brief.kind)}</span>
        ${artMarkup(art, brief.shortDate)}
      </div>
      <div class="card-body">
        <div class="chips">
          <span class="chip">${escapeHtml(`${brief.weekday} · ${brief.dateLabel}`)}</span>
          <span class="chip">${brief.storyCount} stories</span>
        </div>
        <h4>${escapeHtml(brief.theme || brief.title)}</h4>
        ${brief.deck ? `<p class="summary">${escapeHtml(brief.deck)}</p>` : ''}
      </div>
      <div class="card-foot">
        <button class="btn" data-route="${escapeHtml(brief.slug)}">Open cards</button>
        <span class="spacer"></span>
        <a href="${escapeHtml(brief.file)}" target="_blank" rel="noopener">Full briefing ${icon.external}</a>
      </div>
    </article>`;
}

const TOPIC_LABELS = {
  all: 'All stories', ai: 'AI', openai: 'OpenAI', mcp: 'MCP', qa: 'QA',
  ui: 'UI', api: 'API', world: 'World news',
};

function topicFilters(topics) {
  if (topics.length < 2) return '';
  const label = (topic) => TOPIC_LABELS[topic] ?? topic.replace(/^\w/, (c) => c.toUpperCase());
  return `
    <div class="filters" role="group" aria-label="Filter stories by topic">
      ${['all', ...topics].map((topic) => `
        <button class="chip-btn" data-topic="${escapeHtml(topic)}" aria-pressed="${state.topic === topic}">${escapeHtml(label(topic))}</button>`).join('')}
    </div>`;
}

function renderOverview() {
  const [latest, ...rest] = state.data.briefings;
  els.eyebrow.textContent = 'Dashboard';
  els.title.textContent = 'All briefings';
  els.actions.innerHTML = latest
    ? `<a class="btn btn-primary" href="${escapeHtml(latest.file)}" target="_blank" rel="noopener">Latest briefing ${icon.external}</a>`
    : '';

  if (!latest) {
    els.view.innerHTML = `<div class="empty">No briefings yet. Drop an export into <code>public/briefings</code> and rebuild.</div>`;
    return;
  }

  els.view.innerHTML = `
    <section class="hero ${accentClass('blue')}">
      <div class="kicker">${escapeHtml(latest.kicker || `Latest · ${KIND_LABEL[latest.kind]} briefing`)}</div>
      <h2>${escapeHtml(latest.theme || latest.title)}</h2>
      ${latest.deck ? `<p class="deck">${escapeHtml(latest.deck)}</p>` : ''}
      <div class="hero-meta">
        <span class="pill"><span class="pulse"></span>${escapeHtml(`${latest.weekday}, ${latest.dateLabel}`)}</span>
        <span class="pill">${latest.storyCount} stories</span>
        <button class="btn btn-primary" data-route="${escapeHtml(latest.slug)}">Open story cards</button>
        <a class="btn" href="${escapeHtml(latest.file)}" target="_blank" rel="noopener">Full briefing ${icon.external}</a>
      </div>
    </section>

    <section class="stack">
      <div class="section-head">
        <h3>Briefing library</h3>
        <p>${state.data.briefings.length} briefings · ${state.data.briefings.reduce((sum, brief) => sum + brief.storyCount, 0)} stories</p>
      </div>
      <div class="cards">${state.data.briefings.map((brief, index) => briefCard(brief, index)).join('')}</div>
    </section>

    ${rest.length ? `
      <section class="stack">
        <div class="section-head">
          <h3>Latest stories</h3>
          <p>From ${escapeHtml(latest.dateLabel)}</p>
        </div>
        <div class="cards">${latest.stories.map((story, index) => storyCard(latest, story, index)).join('')}</div>
      </section>` : ''}`;
}

function renderBriefing(brief) {
  els.eyebrow.textContent = `${KIND_LABEL[brief.kind] ?? brief.kind} · ${brief.weekday}, ${brief.dateLabel}`;
  els.title.textContent = brief.theme || brief.title;
  els.actions.innerHTML = `<a class="btn btn-primary" href="${escapeHtml(brief.file)}" target="_blank" rel="noopener">Full briefing ${icon.external}</a>`;

  const stories = brief.stories.filter((story) => state.topic === 'all' || (story.topics ?? []).includes(state.topic));

  els.view.innerHTML = `
    <section class="hero ${accentClass(brief.stories[0]?.accent ?? 'blue')}">
      <div class="kicker">${escapeHtml(brief.kicker || `${KIND_LABEL[brief.kind]} briefing`)}</div>
      <h2>${escapeHtml(brief.theme || brief.title)}</h2>
      ${brief.deck ? `<p class="deck">${escapeHtml(brief.deck)}</p>` : ''}
      <div class="hero-meta">
        <span class="pill"><span class="pulse"></span>${escapeHtml(`${brief.weekday}, ${brief.dateLabel}`)}</span>
        <span class="pill">${brief.storyCount} stories</span>
        <a class="btn" href="${escapeHtml(brief.file)}" target="_blank" rel="noopener">Open as published ${icon.external}</a>
      </div>
    </section>

    ${brief.glance.length ? `
      <section class="stack">
        <div class="section-head">
          <h3>At a glance</h3>
          <p>Ordered as published in the briefing</p>
        </div>
        <div class="glance">
          ${brief.glance.map((item, index) => `
            <div class="glance-item ${accentClass(ACCENTS[index % ACCENTS.length])}">
              <span class="n">${String(index + 1).padStart(2, '0')}</span>
              <b>${escapeHtml(item.label)}</b>
              <small>${escapeHtml(item.note)}</small>
            </div>`).join('')}
        </div>
      </section>` : ''}

    <section class="stack">
      <div class="section-head">
        <h3>Story cards</h3>
        <p>${stories.length} of ${brief.storyCount} shown</p>
      </div>
      ${topicFilters(brief.topics ?? [])}
      ${stories.length
        ? `<div class="cards">${stories.map((story) => storyCard(brief, story, brief.stories.indexOf(story))).join('')}</div>`
        : `<div class="empty">No stories match this filter.</div>`}
    </section>

    ${brief.watch.length ? `
      <section class="stack">
        <div class="section-head"><h3>Worth watching</h3><p>Signals, not full stories</p></div>
        <div class="watch-grid">
          ${brief.watch.map((item) => `
            <div class="watch-item">
              <b>${escapeHtml(item.label)}</b>
              <span>${escapeHtml(item.note)}</span>
            </div>`).join('')}
        </div>
      </section>` : ''}

    <p class="foot-note">
      Cards are generated from the published briefing. Prompts are starting points, not a substitute for
      firm policy, audit evidence or professional judgment.
    </p>`;
}

function renderSearch() {
  const hits = state.data.briefings.flatMap((brief) => brief.stories
    .map((story, index) => ({ brief, story, index }))
    .filter(({ story }) => matchesQuery(brief, story, state.query)));

  els.eyebrow.textContent = 'Search';
  els.title.textContent = `“${state.query}”`;
  els.actions.innerHTML = `<button class="btn" data-clear-search>Clear search</button>`;
  els.view.innerHTML = `
    <section class="stack">
      <div class="section-head">
        <h3>${hits.length} ${hits.length === 1 ? 'story' : 'stories'} found</h3>
        <p>Across ${state.data.briefings.length} briefings</p>
      </div>
      ${hits.length
        ? `<div class="cards">${hits.map(({ brief, story, index }) => storyCard(brief, story, index, { showSource: true })).join('')}</div>`
        : `<div class="empty">Nothing matched “${escapeHtml(state.query)}”.</div>`}
    </section>`;
}

function render() {
  renderSidebar();
  if (state.query.trim().length > 1) renderSearch();
  else if (state.slug && byId(state.slug)) renderBriefing(byId(state.slug));
  else renderOverview();
}

/* ------------------------------------------------------------------ events */

function navigate(slug, { scroll = true } = {}) {
  state.slug = slug || null;
  state.topic = 'all';
  state.query = '';
  els.search.value = '';
  const hash = slug ? `#/${slug}` : '#/';
  if (location.hash !== hash) history.pushState(null, '', hash);
  document.body.dataset.drawer = 'closed';
  render();
  if (scroll) document.querySelector('.main')?.scrollTo({ top: 0, behavior: 'instant' });
}

function readHash() {
  const slug = decodeURIComponent(location.hash.replace(/^#\/?/, '')).trim();
  state.slug = slug && byId(slug) ? slug : null;
}

document.addEventListener('click', async (event) => {
  const route = event.target.closest('[data-route]');
  if (route) {
    navigate(route.dataset.route);
    return;
  }

  const topic = event.target.closest('[data-topic]');
  if (topic) {
    state.topic = topic.dataset.topic;
    render();
    return;
  }

  const copy = event.target.closest('[data-copy]');
  if (copy) {
    const text = document.querySelector(`[data-prompt="${copy.dataset.copy}"] code`)?.textContent ?? '';
    toast(await copyText(text) ? 'Prompt copied' : 'Copy failed — select the text instead');
    return;
  }

  const expand = event.target.closest('[data-expand]');
  if (expand) {
    const block = document.querySelector(`[data-prompt="${expand.dataset.expand}"]`);
    const open = block?.classList.toggle('open');
    expand.textContent = open ? 'Show less' : 'Show full';
    return;
  }

  if (event.target.closest('[data-clear-search]')) {
    els.search.value = '';
    state.query = '';
    render();
    return;
  }

  if (event.target.closest('[data-menu]')) {
    document.body.dataset.drawer = document.body.dataset.drawer === 'open' ? 'closed' : 'open';
    return;
  }

  if (event.target.closest('.backdrop')) document.body.dataset.drawer = 'closed';

  const themeToggle = event.target.closest('[data-theme-toggle]');
  if (themeToggle) setTheme(document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark');
});

els.search.addEventListener('input', (event) => {
  state.query = event.target.value;
  render();
});

document.addEventListener('keydown', (event) => {
  if (event.key === '/' && document.activeElement !== els.search) {
    event.preventDefault();
    els.search.focus();
  }
  if (event.key === 'Escape') {
    document.body.dataset.drawer = 'closed';
    if (state.query) {
      els.search.value = '';
      state.query = '';
      render();
    }
  }
});

window.addEventListener('popstate', () => {
  readHash();
  state.query = '';
  els.search.value = '';
  render();
});

/* ------------------------------------------------------------------- theme */

function setTheme(theme) {
  document.documentElement.dataset.theme = theme;
  try { localStorage.setItem('briefing-theme', theme); } catch { /* private mode */ }
  const button = document.querySelector('[data-theme-toggle]');
  if (button) {
    button.innerHTML = theme === 'dark' ? icon.sun : icon.moon;
    button.setAttribute('aria-label', theme === 'dark' ? 'Switch to light theme' : 'Switch to dark theme');
  }
}

function initTheme() {
  let stored = null;
  try { stored = localStorage.getItem('briefing-theme'); } catch { /* private mode */ }
  setTheme(stored ?? (matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light'));
}

/* -------------------------------------------------------------------- boot */

initTheme();

try {
  const response = await fetch('data/briefings.json', { cache: 'no-cache' });
  if (!response.ok) throw new Error(`manifest ${response.status}`);
  state.data = await response.json();
} catch (error) {
  els.view.innerHTML = `<div class="empty">Could not load the briefing manifest (${escapeHtml(error.message)}).
    Run <code>npm run build</code> to regenerate <code>public/data/briefings.json</code>.</div>`;
  throw error;
}

els.count.textContent = `${state.data.briefings.length} briefing${state.data.briefings.length === 1 ? '' : 's'}`;
readHash();
render();
